test('erases whole annotations with one undo per gesture and preserves overlapping shapes', async ({ page }, testInfo) => {
  await page.goto('')
  await page.getByTestId('canvas-annotation-mode').click()
  await drag(page, [260, 140], [400, 140])
  await drag(page, [260, 220], [400, 220])
  const before = await snapshot(page)
  const board = page.getByTestId('breadboard-canvas')
  const eraser = page.getByRole('button', { name: '橡皮擦', exact: true })
  await eraser.click()
  await expect(eraser).toHaveAttribute('aria-pressed', 'true')
  expect(await eraser.evaluate(node => node.nextElementSibling?.getAttribute('aria-label'))).toBe('清空标注')
  await page.screenshot({ path: testInfo.outputPath('annotation-eraser.png') })
  // Travel across both complete strokes; one undo restores both.
  await drag(page, [330, 100], [330, 250])
  await expect(board).toHaveAttribute('data-annotation-count', '0')
  expect((await snapshot(page)).annotationPast).toHaveLength(before.annotationPast.length + 1)
  expect((await snapshot(page)).document).toEqual(before.document)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  expect((await snapshot(page)).annotations).toEqual(before.annotations)
  // Blank areas don't create history entries, and hovering does not erase.
  const blank = await point(page, 650, 140)
  await page.mouse.click(blank.x, blank.y)
  const onStroke = await point(page, 330, 140)
  await page.mouse.move(onStroke.x, onStroke.y)
  expect((await snapshot(page)).annotations).toEqual(before.annotations)
  await page.mouse.down()
  await page.keyboard.press('Escape')
  await page.mouse.up()
  expect((await snapshot(page)).annotations).toEqual(before.annotations)
  await expect(board).toHaveAttribute('data-annotation-mode', 'true')
  // Rectangle hit testing follows its outline, not its empty interior.
  await page.getByRole('button', { name: '方框', exact: true }).click()
  await drag(page, [280, 130], [380, 230])
  await eraser.click()
  const middle = await point(page, 330, 180)
  await page.mouse.click(middle.x, middle.y)
  await expect(board).toHaveAttribute('data-annotation-count', '3')
  // Erase the outline where it overlaps a stroke: only the top rectangle goes.
  const crossing = await point(page, 280, 140)
  await page.mouse.click(crossing.x, crossing.y)
  expect((await snapshot(page)).annotations).toEqual(before.annotations)
  await page.getByTestId('canvas-fullscreen').click()
  const zoomed = await point(page, 330, 140)
  await page.mouse.click(zoomed.x, zoomed.y)
  expect((await snapshot(page)).annotations).toEqual([before.annotations[1]])
})

test('erases arrowheads, text and pen dots, and cancels touch erasing when pinching', async ({ page, context }) => {
  await page.goto('')
  await page.getByTestId('canvas-annotation-mode').click()
  const dot = await point(page, 300, 140)
  await page.mouse.click(dot.x, dot.y)
  await page.getByRole('button', { name: '箭头', exact: true }).click()
  await drag(page, [450, 140], [600, 140])
  await page.getByRole('button', { name: '文字', exact: true }).click()
  const text = await point(page, 300, 230)
  await page.mouse.click(text.x, text.y)
  await page.getByLabel('标注文字').fill('教学标注')
  await page.getByRole('button', { name: '完成', exact: true }).click()
  const before = await snapshot(page)
  const eraser = page.getByRole('button', { name: '橡皮擦', exact: true })
  await eraser.click()
  const board = page.getByTestId('breadboard-canvas')
  const cdp = await context.newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...dot, id: 1 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...dot, id: 1 }, { x: dot.x + 150, y: dot.y, id: 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  expect((await snapshot(page)).annotations).toEqual(before.annotations)
  await page.mouse.click(dot.x, dot.y)
  await expect(board).toHaveAttribute('data-annotation-count', '2')
  const head = await point(page, 594, 143)
  await page.mouse.click(head.x, head.y)
  await expect(board).toHaveAttribute('data-annotation-count', '1')
  await page.mouse.click(text.x + 4, text.y + 4)
  await expect(board).toHaveAttribute('data-annotation-count', '0')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  expect((await snapshot(page)).annotations[0].text).toBe('教学标注')
})
